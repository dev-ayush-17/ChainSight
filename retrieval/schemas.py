"""Pydantic data models for intent classification, query retrieval results, and context assembly."""

from typing import Literal

from pydantic import BaseModel, Field

IntentType = Literal["lookup", "impact_traversal", "semantic", "unanswerable"]
RetrievalStrategyType = Literal["text_to_cypher", "impact_traversal", "vector_search", "refused"]


class IntentClassification(BaseModel):
    """Result of intent router classification on user query."""

    intent: IntentType = Field(..., description="Classified query intent")
    confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence score")
    reasoning: str = Field(..., description="Explanation of routing decision")
    extracted_entities: list[str] = Field(
        default_factory=list, description="Named entities identified in question"
    )
    disruption_keywords: list[str] = Field(
        default_factory=list, description="Keywords signaling supply chain disruption"
    )


class TraversalImpactResult(BaseModel):
    """Result of parameterized Cypher graph traversal strategy."""

    template_name: str = Field(..., description="Name of executed traversal template")
    parameters: dict[str, str | int | float | bool] = Field(
        default_factory=dict, description="Parameters bound to template"
    )
    records: list[dict[str, str | int | float | bool]] = Field(
        default_factory=list, description="Tabular rows returned by traversal"
    )
    subgraph_node_ids: list[str] = Field(
        default_factory=list, description="Node IDs traversed for visualization"
    )
    subgraph_edge_ids: list[str] = Field(
        default_factory=list, description="Edge IDs traversed for visualization"
    )


class VectorSearchResult(BaseModel):
    """Single ranked article chunk with expanded graph neighborhood."""

    chunk_id: str = Field(..., description="Unique article chunk identifier")
    title: str = Field(..., description="Article headline")
    source: str = Field(..., description="News publication or source")
    published_date: str = Field(..., description="Publication date YYYY-MM-DD")
    text: str = Field(..., description="Chunk text content")
    score: float = Field(..., description="Cosine similarity score")
    mentioned_node_ids: list[str] = Field(
        default_factory=list, description="Entities directly connected via MENTIONS"
    )
    expanded_node_ids: list[str] = Field(
        default_factory=list, description="1-hop neighborhood entities"
    )


class CypherQueryResult(BaseModel):
    """Result of LLM-generated Cypher query validation and execution."""

    generated_cypher: str = Field(..., description="Cypher query generated by LLM")
    is_safe: bool = Field(..., description="Whether query passed read-only safety guardrails")
    records: list[dict[str, str | int | float | bool]] = Field(
        default_factory=list, description="Execution result rows"
    )
    subgraph_node_ids: list[str] = Field(
        default_factory=list, description="Node IDs retrieved for visualization"
    )
    error_message: str | None = Field(default=None, description="Execution error if any")


class RetrievedContext(BaseModel):
    """Unified context assembled across retrieval strategies for downstream generation."""

    strategy: RetrievalStrategyType = Field(..., description="Retrieval strategy executed")
    raw_query: str = Field(..., description="Original user prompt")
    structured_records: list[dict[str, str | int | float | bool]] = Field(
        default_factory=list, description="Tabular graph data from Cypher or traversal"
    )
    text_passages: list[str] = Field(
        default_factory=list, description="Relevant news text passages"
    )
    subgraph_node_ids: list[str] = Field(
        default_factory=list, description="Unified node IDs for visualization"
    )
    subgraph_edge_ids: list[str] = Field(
        default_factory=list, description="Unified edge IDs for visualization"
    )
